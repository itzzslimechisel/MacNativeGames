#!/usr/bin/env python3
"""Host-trap signatures of the NVN entry points for the dynarmic (x86-64) build (docs/windows-port-plan.md C19).

The NVN layer (third_party/d2r_gfx/gfx/nvn/hle_nvn.c) hands the guest one entry per NVN name. Under the JIT each entry is
a host trap that marshals the guest's AAPCS64 arguments by a signature string (runtime/cpu_backend.h: return char, ':',
one char per argument; 'i' integer/pointer, 'f' float, 'd' double, 'v' void). This script derives those strings from the
generated prototypes (nvn_protos.h) in the order of the thunk name table (names.txt) and writes a C header:

    static const char *const nvn_jit_sigs[NVN_NFUNC] = { "v:i", ... };   /* NULL: no prototype (unimplemented) */
    #define NVN_JIT_NAME_LIST "nvnDeviceBuilderSetDefaults", ...        /* names.txt */

Entries with by-value structs get no signature (comment "by-value struct"): the runtime refuses to bind them if the NVN
layer implements one. Varargs or more than 8 arguments stop the script.
Usage: gen_nvn_traps.py <nvn dir> <output header>
"""
import re
import sys
from pathlib import Path

nvn = Path(sys.argv[1])
out = Path(sys.argv[2])
names = (nvn / 'names.txt').read_text(encoding='utf-8').split()
protos = (nvn / 'nvn_protos.h').read_text(encoding='utf-8')
header = (nvn / 'include' / 'nvn.h').read_text(encoding='utf-8')

structs = set(re.findall(r'\}\s*(NVN\w+)\s*;', header)) - set(re.findall(r'typedef\s+enum\s*\{[^}]*\}\s*(NVN\w+)\s*;', header, re.S))
scalars = {'int', 'unsigned', 'int32_t', 'uint32_t', 'int64_t', 'uint64_t', 'int16_t', 'uint16_t', 'int8_t', 'uint8_t',
           'size_t', 'ptrdiff_t', 'intptr_t', 'uintptr_t', 'char', 'long', 'short', 'bool', '_Bool'}
scalars |= set(re.findall(r'typedef\s+(?:u?int\w*|int|void\s*\*)\s+(NVN\w+)\s*;', header))
scalars |= set(re.findall(r'typedef\s+enum\s*\{[^}]*\}\s*(NVN\w+)\s*;', header, re.S))
# One-word structs (NVNseparateTextureHandle): an x register in AAPCS64, a register in Win64 too.
scalars |= set(re.findall(r'typedef\s+struct\s*\{\s*u?int(?:64|32)_t\s+\w+;\s*\}\s*(NVN\w+)\s*;', header))


def kind(t, what):
    t = t.strip()
    if not t or t == 'void':
        return 'v'
    if '*' in t or re.search(r'\bPFN\w*PROC\b', t):   # function pointer typedefs
        return 'i'
    base = re.sub(r'\b(const|volatile|unsigned|signed)\b', '', t).split()
    base = base[-1] if base else 'int'
    if base == 'float':
        return 'f'
    if base == 'double':
        return 'd'
    if base in scalars or ('unsigned' in t.split()):
        return 'i'
    if base in structs:
        raise ValueError(f'by-value struct {t}')
    sys.exit(f'{what}: unknown type {t!r}')


sigs, skipped = {}, {}
for ret, name, args in re.findall(r'typedef\s+(.+?)\s*\(\*NVNT_(\w+)\)\((.*?)\);', protos):
    params = [a for a in (x.strip() for x in args.split(',')) if a and a != 'void']
    if '...' in params:
        sys.exit(f'{name}: varargs')
    if len(params) > 8:
        sys.exit(f'{name}: more than 8 arguments')
    try:
        sigs[name] = kind(ret, name) + ':' + ''.join(kind(p, name) for p in params)
    except ValueError as e:
        skipped[name] = str(e)

lines = ['/* Generated by tools/windows/gen_nvn_traps.py from nvn_protos.h and names.txt; do not edit. */',
         '#pragma once', '#include "nvn_count.h"',
         'static const char *const nvn_jit_sigs[NVN_NFUNC] = {']
for n in names:
    note = skipped.get(n, 'no prototype')
    lines.append(f'    "{sigs[n]}", /* {n} */' if n in sigs else f'    0, /* {n}: {note} */')
lines.append('};')
lines.append('/* The thunk name table (nvn_thunks.S nvn_names), for nvn_jit.c. */')
lines.append('#define NVN_JIT_NAME_LIST ' + chr(92))
lines += [f'    "{n}", ' + chr(92) for n in names]
lines.append('')
if len(names) != int(re.search(r'NVN_NFUNC (\d+)', (nvn / 'nvn_count.h').read_text(encoding='utf-8')).group(1)):
    sys.exit('names.txt does not match NVN_NFUNC')
out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'{out}: {len(names)} entries, {sum(n in sigs for n in names)} with prototypes')
