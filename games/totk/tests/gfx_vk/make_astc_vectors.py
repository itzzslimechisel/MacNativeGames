#!/usr/bin/env python3
"""Generates astc_vectors.h for test_astc_dec.c: reference ASTC blocks decoded by ARM's astcenc (the reference codec).

  make_astc_vectors.py <astcenc executable> <work dir> [out header]

Synthetic 48x48 RGBA images (noise, gradients, hard edges, alpha ramps) are compressed at several block footprints and
qualities (so multi-partition, dual-plane and every endpoint mode class appear), as LDR and sRGB, then decompressed by
astcenc with the LDR / sRGB profile; each block and its decoded texels become one vector."""
import os, random, struct, subprocess, sys

W = H = 48

def tga_write(path, px):
    with open(path, "wb") as f:
        f.write(struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, W, H, 32, 0x28))   # top-left origin
        for r, g, b, a in px:
            f.write(bytes((b, g, r, a)))

def tga_read(path):
    d = open(path, "rb").read()
    idlen, cmtype, itype = d[0], d[1], d[2]
    w, h, bpp, desc = struct.unpack("<HHBB", d[12:18])
    off = 18 + idlen
    if itype not in (2, 10) or bpp not in (24, 32):
        raise SystemExit(f"unsupported TGA from astcenc: type {itype} bpp {bpp}")
    n = bpp // 8
    flat = []
    if itype == 2:
        flat = [d[off + i * n: off + (i + 1) * n] for i in range(w * h)]
    else:   # run-length encoded
        p = off
        while len(flat) < w * h:
            c = d[p]; p += 1; cnt = (c & 0x7F) + 1
            if c & 0x80: flat += [d[p:p + n]] * cnt; p += n
            else: flat += [d[p + i * n: p + (i + 1) * n] for i in range(cnt)]; p += cnt * n
    rows = [[(q[2], q[1], q[0], q[3] if n == 4 else 255) for q in flat[y * w:(y + 1) * w]] for y in range(h)]
    if not (desc & 0x20):
        rows.reverse()
    return rows

def images(rng):
    yield "noise", [(rng.randrange(256), rng.randrange(256), rng.randrange(256), rng.randrange(256)) for _ in range(W * H)]
    yield "grad", [((x * 255) // (W - 1), (y * 255) // (H - 1), ((x + y) * 255) // (W + H - 2), 255) for y in range(H) for x in range(W)]
    yield "edges", [((255, 20, 20, 255) if (x // 5 + y // 7) % 3 == 0 else (10, 200, 60, 128) if (x * y) % 11 < 4 else (30, 40, 230, 255)) for y in range(H) for x in range(W)]
    yield "alpha", [(200, 120, 40, (x * 7 + y * 3) % 256) for y in range(H) for x in range(W)]
    yield "lum", [(v, v, v, 255) for y in range(H) for x in range(W) for v in [((x ^ y) * 5) % 256]]
    yield "lumalpha", [(v, v, v, (y * 255) // (H - 1)) for y in range(H) for x in range(W) for v in [(x * 255) // (W - 1)]]

def main():
    astcenc, work = sys.argv[1], sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "astc_vectors.h")
    os.makedirs(work, exist_ok=True)
    rng = random.Random(1234)
    vecs = []
    for name, px in images(rng):
        src = os.path.join(work, name + ".tga"); tga_write(src, px)
        for fp in ("4x4", "5x4", "5x5", "6x6", "8x5", "8x8", "10x6", "10x10", "12x12"):
            for srgb in (0, 1):
                for q in ("-fast", "-thorough"):
                    a = os.path.join(work, f"{name}_{fp}_{srgb}{q}.astc"); d = a + ".tga"
                    cflag, dflag = ("-cs", "-ds") if srgb else ("-cl", "-dl")
                    subprocess.run([astcenc, cflag, src, a, fp, q, "-silent"], check=True)
                    subprocess.run([astcenc, dflag, a, d, "-silent"], check=True)
                    blob = open(a, "rb").read()
                    bw, bh = blob[4], blob[5]
                    rows = tga_read(d)
                    nbx, nby = (W + bw - 1) // bw, (H + bh - 1) // bh
                    blocks = [(bx, by) for by in range(nby) for bx in range(nbx) if (bx + 1) * bw <= W and (by + 1) * bh <= H]
                    rng.shuffle(blocks)
                    for bx, by in blocks[:4]:
                        k = by * nbx + bx
                        blk = blob[16 + 16 * k: 32 + 16 * k]
                        texels = [c for y in range(bh) for x in range(bw) for c in rows[by * bh + y][bx * bw + x]]
                        vecs.append((bw, bh, srgb, blk, texels))
    with open(out, "w") as f:
        f.write("/* Generated by make_astc_vectors.py from astcenc 5.2 (ARM reference codec) output. Do not edit. */\n")
        f.write(f"static const int NVECS = {len(vecs)};\nstatic const astc_vec VECS[{len(vecs)}] = {{\n")
        for bw, bh, srgb, blk, tx in vecs:
            f.write(f" {{{bw}, {bh}, {srgb}, {{{','.join(str(b) for b in blk)}}}, {{{','.join(str(t) for t in tx)}}}}},\n")
        f.write("};\n")
    print(f"{len(vecs)} vectors -> {out}")

if __name__ == "__main__":
    main()
